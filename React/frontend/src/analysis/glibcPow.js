function decompose(x) { // x = m * 2^e with signed BigInt m
  if (x === 0) return [0n, 0]
  f64[0] = Math.abs(x)
  const bits = u64[0]
  const ex = Number((bits >> 52n) & 0x7ffn)
  let m = bits & 0xfffffffffffffn
  let e
  if (ex === 0) e = -1074
  else {
    m |= 1n << 52n
    e = ex - 1075
  }
  return [x < 0 ? -m : m, e]
}

/** Correctly rounded a*b + c (single rounding), via BigInt. Slow path of fma(). */
export function fmaExact(a, b, c) {
  const naive = a * b + c
  if (!Number.isFinite(naive) || a === 0 || b === 0) return naive
  const [ma, ea] = decompose(a)
  const [mb, eb] = decompose(b)
  const [mc, ec] = decompose(c)
  const mp = ma * mb
  const ep = ea + eb
  let m
  let e
  if (mc === 0n) {
    m = mp
    e = ep
  } else {
    e = Math.min(ep, ec)
    if (ep - e > 1500 || ec - e > 1500) return naive
    m = (mp << BigInt(ep - e)) + (mc << BigInt(ec - e))
  }
  if (m === 0n) return 0
  const neg = m < 0n
  if (neg) m = -m
  const bl = m.toString(2).length
  if (bl > 120) { // keep 120 bits plus a sticky bit so Number() still rounds correctly
    const sh = BigInt(bl - 120)
    const sticky = (m & ((1n << sh) - 1n)) !== 0n
    m = ((m >> sh) << 1n) | (sticky ? 1n : 0n)
    e += Number(sh) - 1
  }
  let r = Number(m) // ECMAScript: round to nearest, ties to even
  while (e > 0) {
    const s = Math.min(e, 1000)
    r *= Math.pow(2, s)
    e -= s
  }
  while (e < 0) {
    const s = Math.min(-e, 1000)
    r *= Math.pow(2, -s)
    e += s
  }
  return neg ? -r : r
}

const SPLIT = 134217729 // 2^27 + 1

/** a*b + c with a single rounding. Double-double fast path, BigInt only near rounding ties. */
export function fma(a, b, c) {
  const p = a * b
  const ap = Math.abs(p)
  if (!(ap < 1e290 && ap > 1e-290) || !(Math.abs(c) < 1e290)) return fmaExact(a, b, c)
  let t = SPLIT * a
  const ah = t - (t - a)
  const al = a - ah
  t = SPLIT * b
  const bh = t - (t - b)
  const bl = b - bh
  const pl = ((ah * bh - p) + ah * bl + al * bh) + al * bl // p + pl == a*b exactly
  const s = p + c
  const bb = s - p
  const e1 = (p - (s - bb)) + (c - bb) // s + e1 == p + c exactly
  const l = e1 + pl
  const bb2 = l - e1
  const l2 = (e1 - (l - bb2)) + (pl - bb2) // l + l2 == e1 + pl exactly
  const r = s + l
  const bb3 = r - s
  const rem = (s - (r - bb3)) + (l - bb3) // r + rem == s + l exactly
  if (r === 0) return fmaExact(a, b, c)
  f64[0] = r
  const ex = (u32[1] >>> 20) & 0x7ff
  if (ex < 100 || ex > 1900) return fmaExact(a, b, c)
  u32[1] = (ex - 53) << 20 // half ulp of r
  u32[0] = 0
  const halfUlp = f64[0]
  if (Math.abs(rem) + Math.abs(l2) < halfUlp * 0.999) return r
  return fmaExact(a, b, c)
}

// ------------------------------------------------------------------ pow
/**
 * glibc pow(x, y) for x > 0 (see header). Outside the supported range
 * (x not a positive normal, |y| outside [2^-65, 2^63), or |x^y| overflow-ish
 * results) falls back to Math.pow.
 */
export function powGlibc(x, y) {
  const ay = Math.abs(y)
  if (!(x >= 2.2250738585072014e-308 && x < Infinity) || !(ay >= 2.710505431213761e-20 && ay < 9.223372036854776e18)) {
    return Math.pow(x, y)
  }
  f64[0] = x
  const xhi = u32[1]
  const xlo = u32[0]
  // log_inline
  const tmpHi = (xhi - 0x3fe69555) >>> 0 // OFF = 0x3fe6955500000000
  const i = ((tmpHi >>> 13) & 127) * 3
  const kd = (tmpHi | 0) >> 20
  u32[1] = (xhi - (tmpHi & 0xfff00000)) >>> 0
  u32[0] = xlo
  const z = f64[0]
  const invc = LOG_TAB[i]
  const logc = LOG_TAB[i + 1]
  const logctail = LOG_TAB[i + 2]
  const r = fma(z, invc, -1.0)
  const t1 = fma(kd, LN2HI, logc)
  const t2 = t1 + r
  const lo1 = fma(kd, LN2LO, logctail)
  const lo2 = t1 - t2 + r
  const ar = A0 * r
  const ar2 = r * ar
  const ar3 = r * ar2
  const hi = t2 + ar2
  const lo3 = fma(ar, r, -ar2)
  const lo4 = t2 - hi + ar2
  const q = fma(ar2, fma(ar2, fma(r, A6, A5), fma(r, A4, A3)), fma(r, A2, A1))
  const p = ar3 * q
  const lo = lo1 + lo2 + lo3 + lo4 + p
  const yy = hi + lo
  const tail = hi - yy + lo
  // y * log(x) as a double-double
  const ehi = y * yy
  const elo = fma(y, tail, fma(y, yy, -ehi))
  // exp_inline
  const ae = Math.abs(ehi)
  if (ae < 5.551115123125783e-17) return 1.0 + ehi // |x| < 2^-54
  if (!(ae < 512)) return Math.pow(x, y)
  const kd2 = fma(INV_LN2_N, ehi, SHIFT)
  f64[0] = kd2
  const kiLo = u32[0]
  const kdr = kd2 - SHIFT
  let rr = fma(kdr, NEG_LN2LO_N, fma(kdr, NEG_LN2HI_N, ehi))
  rr += elo
  const idx = 2 * (kiLo & 127)
  const tl = ETAB_F64[idx]
  const sHi = (ETAB_U32[2 * idx + 3] + ((kiLo << 13) >>> 0)) >>> 0
  const sLo = ETAB_U32[2 * idx + 2]
  const r2 = rr * rr
  let tm = fma(r2, fma(rr, C3, C2), tl + rr)
  tm = fma(r2 * r2, fma(rr, C5, C4), tm)
  u32[1] = sHi
  u32[0] = sLo
  const scale = f64[0]
  return fma(scale, tm, scale)
}

/**
 * Python `x ** 2` for a float x (libm pow(x, 2.0)). Equals x*x except in the
 * ~0.09% of cases where glibc's pow lands on the other neighbour; those are
 * detected via the exact product error and resolved with powGlibc.
 */
export function pow2(x) {
  const p = x * x
  const ap = Math.abs(p)
  if (ap > 1e-290 && ap < 1e290) {
    let t = SPLIT * x
    const xh = t - (t - x)
    const xl = x - xh
    const pl = ((xh * xh - p) + 2 * xh * xl) + xl * xl // p + pl == x*x exactly
    f64[0] = p
    const ex = (u32[1] >>> 20) & 0x7ff
    u32[1] = (ex - 52) << 20
    u32[0] = 0
    const ulp = f64[0]
    if (Math.abs(pl) < 0.44 * ulp) return p
  }
  return powGlibc(x, 2)
}
